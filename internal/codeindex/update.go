const (
	maxScanSize = 1 << 20   // bigger files are skipped entirely
	maxBodySize = 120 << 10 // bigger files are scanned for symbols but not full-text indexed
	racySlack   = 2 * time.Second
)

// UpdateStats says what an Update did.
type UpdateStats struct {
	Files      int           `json:"files"`
	Added      int           `json:"added"`
	Changed    int           `json:"changed"`
	Removed    int           `json:"removed"`
	Symbols    int           `json:"symbols"`
	Commits    int           `json:"commits"`     // commits in the history window
	NewCommits int           `json:"new_commits"` // read this time
	Head       string        `json:"head"`
	Duration   time.Duration `json:"duration_ns"`
	ScanTime   time.Duration `json:"scan_ns"`    // reading and parsing changed files
	WriteTime  time.Duration `json:"write_ns"`   // writing them to the database
	GitTime    time.Duration `json:"history_ns"` // reading and folding git history
}

// skipDirs are directory names whose contents are never indexed.
var skipDirs = map[string]bool{
	"node_modules": true, "vendor": true, "dist": true, "build": true, "target": true, "__pycache__": true,
	".venv": true, "venv": true, "site-packages": true, ".git": true, "staticfiles": true, "htmlcov": true,
	"coverage": true, ".next": true, ".cache": true, ".mypy_cache": true, ".pytest_cache": true, ".tox": true, "bin": false,
}

var skipNames = map[string]bool{
	"package-lock.json": true, "yarn.lock": true, "pnpm-lock.yaml": true, "go.sum": true, "cargo.lock": true,
	"poetry.lock": true, "uv.lock": true, "pipfile.lock": true, "composer.lock": true, "gemfile.lock": true,
}

// skipPath is true for paths we never read: vendored, built, lock files,
// minified and data files.
func skipPath(p string) bool {
	parts := strings.Split(p, "/")
	for _, d := range parts[:len(parts)-1] {
		if skipDirs[strings.ToLower(d)] {
			return true
		}
	}
	base := strings.ToLower(parts[len(parts)-1])
	if skipNames[base] || strings.HasSuffix(base, ".min.js") || strings.HasSuffix(base, ".min.css") || strings.HasSuffix(base, ".map") ||
		strings.HasSuffix(base, ".snap") || strings.HasSuffix(base, ".pb.go") || strings.HasSuffix(base, "_generated.go") || strings.HasSuffix(base, ".gen.go") {
		return true
	}
	return Language(p) == ""
}

// generated is true for files that say they are generated.
func generated(src []byte) bool {
	head := src[:min(len(src), 1024)]
	for _, m := range [][]byte{[]byte("Code generated"), []byte("DO NOT EDIT"), []byte("@generated"), []byte("Auto-generated"), []byte("auto-generated by")} {
		if bytes.Contains(head, m) {
			return true
		}
	}
	return false
}

// listFiles returns the checkout's files: tracked plus untracked and not
// ignored, in git's order, filtered by skipPath.
func (ix *Index) listFiles() ([]string, error) {
	out, err := gitOut(ix.Root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
	if err != nil {
		return nil, err
	}
	var files []string
	seen := map[string]bool{}
	for _, f := range strings.Split(out, "\x00") {
		if f == "" || seen[f] || skipPath(f) {
			continue
		}
		seen[f] = true
		files = append(files, f)
	}
	return files, nil
}

type fileRow struct {
	id      int64
	size    int64
	mtimeNS int64
	idxNS   int64
	hash    string
}

// fresh is the result of reading and scanning one changed file.
type fresh struct {
	path    string
	lang    string
	size    int64
	mtimeNS int64
	hash    string
	lines   int
	parsed  Parsed
	body    string
	skip    bool // binary, generated or unreadable: not indexed
	same    bool // content hash unchanged: only the mtime moved
}

// Update brings the index up to date with the working tree and HEAD:
// files whose size or mtime moved are re-hashed and, if their content
// changed, re-scanned; new commits are folded into the history signals.
// When nothing changed it writes nothing.
func (ix *Index) Update(ctx context.Context) (UpdateStats, error) {
	start := time.Now()
	st := UpdateStats{}
	head := ""
	if out, err := gitOut(ix.Root, "rev-parse", "--verify", "-q", "HEAD"); err == nil {
		head = strings.TrimSpace(out)
	}
	st.Head = head
	files, err := ix.listFiles()
	if err != nil {
		return st, fmt.Errorf("git ls-files: %w", err)
	}
	old, err := ix.loadFiles()
	if err != nil {
		return st, err
	}
	skipped, err := ix.loadSkipped()
	if err != nil {
		return st, err
	}

	// Which files need a look: new ones, and ones whose stat moved (or is
	// too recent to trust, git's "racy" case).
	var look []string
	present := make(map[string]bool, len(files))
	for _, f := range files {
		fi, err := os.Lstat(filepath.Join(ix.Root, filepath.FromSlash(f)))
		if err != nil || !fi.Mode().IsRegular() || fi.Size() > maxScanSize {
			continue
		}
		present[f] = true
		r, ok := old[f]
		if ok && r.size == fi.Size() && r.mtimeNS == fi.ModTime().UnixNano() && r.mtimeNS < r.idxNS-int64(racySlack) {
			continue
		}
		if sk, ok := skipped[f]; ok && sk.size == fi.Size() && sk.mtimeNS == fi.ModTime().UnixNano() && time.Since(fi.ModTime()) > racySlack {
			continue
		}
		look = append(look, f)
	}
	var gone []string
	for p := range old {
		if !present[p] {
			gone = append(gone, p)
		}
	}
	slices.Sort(gone)

	t0 := time.Now()
	results := ix.readAll(ctx, look, old)
	st.ScanTime = time.Since(t0)
	if err := ctx.Err(); err != nil {
		return st, err
	}
	changed := make([]fresh, 0, len(results))
	var newlySkipped []fresh
	for _, r := range results {
		if r.skip {
			if _, ok := old[r.path]; ok {
				gone = append(gone, r.path)
			}
			if r.mtimeNS != 0 {
				newlySkipped = append(newlySkipped, r)
			}
			continue
		}
		changed = append(changed, r)
	}
	needHistory := head != "" && head != ix.meta("history_head")
	needWrite := len(changed) > 0 || len(gone) > 0 || needHistory || len(newlySkipped) > 0
	if needWrite {
		tx, err := ix.db.BeginTx(ctx, nil)
		if err != nil {
			return st, err
		}
		defer func() { _ = tx.Rollback() }()
		t1 := time.Now()
		if err := ix.writeFiles(tx, old, changed, gone, &st); err != nil {
			return st, err
		}
		st.WriteTime = time.Since(t1)
		for _, r := range newlySkipped {
			if _, err := tx.Exec(`INSERT INTO skipped(path, size, mtime_ns) VALUES (?, ?, ?) ON CONFLICT(path) DO UPDATE SET size = excluded.size, mtime_ns = excluded.mtime_ns`, r.path, r.size, r.mtimeNS); err != nil {
				return st, err
			}
		}
		if _, err := tx.Exec(`DELETE FROM skipped WHERE path IN (SELECT path FROM files)`); err != nil {
			return st, err
		}
		if needHistory {
			t2 := time.Now()
			if err := ix.updateHistory(ctx, tx, head, &st); err != nil {
				return st, err
			}
			st.GitTime = time.Since(t2)
		}
		if err := setMeta(tx, "head", head); err != nil {
			return st, err
		}
		if err := setMeta(tx, "updated_at", fmt.Sprint(time.Now().Unix())); err != nil {
			return st, err
		}
		if err := tx.Commit(); err != nil {
			return st, err
		}
	}
	_ = ix.db.QueryRow(`SELECT count(*) FROM files`).Scan(&st.Files)
	_ = ix.db.QueryRow(`SELECT count(*) FROM symbols`).Scan(&st.Symbols)
	_ = ix.db.QueryRow(`SELECT count(*) FROM commits`).Scan(&st.Commits)
	st.Duration = time.Since(start)
	if needWrite {
		_, _ = ix.db.Exec(`INSERT INTO meta(k, v) VALUES ('last_update_ms', ?) ON CONFLICT(k) DO UPDATE SET v = excluded.v`, fmt.Sprint(st.Duration.Milliseconds()))
	}
	return st, nil
}

type skipRow struct{ size, mtimeNS int64 }

func (ix *Index) loadSkipped() (map[string]skipRow, error) {
	rows, err := ix.db.Query(`SELECT path, size, mtime_ns FROM skipped`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	m := map[string]skipRow{}
	for rows.Next() {
		var p string
		var r skipRow
		if err := rows.Scan(&p, &r.size, &r.mtimeNS); err != nil {
			return nil, err
		}
		m[p] = r
	}
	return m, rows.Err()
}

func (ix *Index) loadFiles() (map[string]fileRow, error) {
	rows, err := ix.db.Query(`SELECT id, path, size, mtime_ns, indexed_ns, hash FROM files`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	m := map[string]fileRow{}
	for rows.Next() {
		var r fileRow
		var p string
		if err := rows.Scan(&r.id, &p, &r.size, &r.mtimeNS, &r.idxNS, &r.hash); err != nil {
			return nil, err
		}
		m[p] = r
	}
	return m, rows.Err()
}

// readAll reads, hashes and scans the files in parallel.
func (ix *Index) readAll(ctx context.Context, paths []string, old map[string]fileRow) []fresh {
	out := make([]fresh, len(paths))
	var wg sync.WaitGroup
	work := make(chan int)
	for range min(runtime.NumCPU(), 8) {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range work {
				out[i] = ix.readOne(paths[i], old)
			}
		}()
	}
	for i := range paths {
		if ctx.Err() != nil {
			break
		}
		work <- i
	}
	close(work)
	wg.Wait()
	return out
}

func (ix *Index) readOne(p string, old map[string]fileRow) fresh {
	f := fresh{path: p, skip: true}
	full := filepath.Join(ix.Root, filepath.FromSlash(p))
	fi, err := os.Stat(full)
	if err != nil {
		return f
	}
	f.size, f.mtimeNS = fi.Size(), fi.ModTime().UnixNano()
	src, err := os.ReadFile(full) // #nosec G304 -- a file git lists in this checkout
	if err != nil || bytes.IndexByte(src[:min(len(src), 8000)], 0) >= 0 || generated(src) {
		return f
	}
	sum := sha1.Sum(src) // #nosec G401 -- change detection only
	f.hash = hex.EncodeToString(sum[:])
	f.size = int64(len(src))
	f.mtimeNS = fi.ModTime().UnixNano()
	f.skip = false
	if o, ok := old[p]; ok && o.hash == f.hash {
		f.same = true
		return f
	}
	f.lang = Language(p)
	f.lines = bytes.Count(src, []byte{'\n'})
	if len(src) > 0 && src[len(src)-1] != '\n' {
		f.lines++
	}
	f.parsed = Scan(f.lang, src)
	if len(src) <= maxBodySize && (path.Ext(p) != ".json" || len(src) <= 40<<10) {
		f.body = strings.ToValidUTF8(string(src), "")
	}
	return f
}

func (ix *Index) writeFiles(tx *sql.Tx, old map[string]fileRow, changed []fresh, gone []string, st *UpdateStats) error {
	now := time.Now().UnixNano()
	for _, p := range gone {
		r := old[p]
		if _, err := tx.Exec(`DELETE FROM files WHERE id = ?`, r.id); err != nil {
			return err
		}
		if _, err := tx.Exec(`DELETE FROM docs WHERE rowid = ?`, r.id); err != nil {
			return err
		}
		st.Removed++
	}
	type pendingImports struct {
		id    int64
		specs []string
		path  string
	}
	var imps []pendingImports
	insSym, err := tx.Prepare(`INSERT INTO symbols(file_id, name, kind, parent, sig, doc, start, decl, end, exported) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`)
	if err != nil {
		return err
	}
	defer func() { _ = insSym.Close() }()
	insDoc, err := tx.Prepare(`INSERT INTO docs(rowid, path, symbols, body) VALUES (?, ?, ?, ?)`)
	if err != nil {
		return err
	}
	defer func() { _ = insDoc.Close() }()
	insImp, err := tx.Prepare(`INSERT INTO imports(file_id, spec) VALUES (?, ?)`)
	if err != nil {
		return err
	}
	defer func() { _ = insImp.Close() }()
	t0 := time.Now()
	for _, f := range changed {
		o, existed := old[f.path]
		if existed && f.same {
			if _, err := tx.Exec(`UPDATE files SET size = ?, mtime_ns = ?, indexed_ns = ? WHERE id = ?`, f.size, f.mtimeNS, now, o.id); err != nil {
				return err
			}
			continue
		}
		var id int64
		if existed {
			id = o.id
			st.Changed++
			if _, err := tx.Exec(`UPDATE files SET lang = ?, size = ?, mtime_ns = ?, indexed_ns = ?, hash = ?, lines = ? WHERE id = ?`, f.lang, f.size, f.mtimeNS, now, f.hash, f.lines, id); err != nil {
				return err
			}
			if _, err := tx.Exec(`DELETE FROM symbols WHERE file_id = ?`, id); err != nil {
				return err
			}
			if _, err := tx.Exec(`DELETE FROM imports WHERE file_id = ?`, id); err != nil {
				return err
			}
			if _, err := tx.Exec(`DELETE FROM docs WHERE rowid = ?`, id); err != nil {
				return err
			}
		} else {
			st.Added++
			res, err := tx.Exec(`INSERT INTO files(path, lang, size, mtime_ns, indexed_ns, hash, lines) VALUES (?, ?, ?, ?, ?, ?, ?)`, f.path, f.lang, f.size, f.mtimeNS, now, f.hash, f.lines)
			if err != nil {
				return err
			}
			if id, err = res.LastInsertId(); err != nil {
				return err
			}
		}
		for _, s := range f.parsed.Symbols {
			if _, err := insSym.Exec(
				id, s.Name, s.Kind, s.Parent, s.Sig, s.Doc, s.Start, s.Decl, s.End, b2i(s.Exported)); err != nil {
				return err
			}
		}
		if _, err := insDoc.Exec(id, ftsPath(f.path), ftsSymbols(f.parsed.Symbols), f.body); err != nil {
			return err
		}
		imps = append(imps, pendingImports{id, f.parsed.Imports, f.path})
	}
	// Import edges: store the specs, then resolve them against the file set.
	for _, im := range imps {
		for _, spec := range dedupe(im.specs) {
			if _, err := insImp.Exec(im.id, spec); err != nil {
				return err
			}
		}
	}
	trace("files written", t0)
	err = ix.resolveImports(tx)
	trace("imports resolved", t0)
	return err
}

func b2i(b bool) int {
	if b {
		return 1
	}
	return 0
}

func dedupe(s []string) []string {
	seen := make(map[string]bool, len(s))
	out := s[:0:0]
	for _, v := range s {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}

// ftsPath is a path as searchable words: the path and its directory and
// file name parts split on separators and case changes.
func ftsPath(p string) string {
	return p + " " + strings.Join(splitWords(strings.TrimSuffix(p, path.Ext(p))), " ")
}

// ftsSymbols is the symbol column of a file: names with their split words,
// and doc lines, so prose queries find things by what they are called and
// what they do.
func ftsSymbols(syms []Symbol) string {
	var b strings.Builder
	for _, s := range syms {
		b.WriteString(s.Name)
		b.WriteByte(' ')
		if w := splitWords(s.Name); len(w) > 1 {
			b.WriteString(strings.Join(w, " "))
			b.WriteByte(' ')
		}
		if s.Parent != "" {
			b.WriteString(s.Parent)
			b.WriteByte(' ')
		}
		if s.Doc != "" {
			b.WriteString(s.Doc)
		}
		b.WriteByte('\n')
	}
	return b.String()
}

// splitWords breaks an identifier or path into lower-case words:
// MergeReady, merge_ready and merge-ready are all [merge ready].
func splitWords(s string) []string {
	var words []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			words = append(words, strings.ToLower(string(cur)))
			cur = cur[:0]
		}
	}
	rs := []rune(s)
	for i, r := range rs {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r > 127:
			cur = append(cur, r)
		case r >= 'A' && r <= 'Z':
			prevLower := i > 0 && (rs[i-1] >= 'a' && rs[i-1] <= 'z' || rs[i-1] >= '0' && rs[i-1] <= '9')
			nextLower := i+1 < len(rs) && rs[i+1] >= 'a' && rs[i+1] <= 'z'
			if len(cur) > 0 && (prevLower || (nextLower && i > 0 && rs[i-1] >= 'A' && rs[i-1] <= 'Z')) {
				flush()
			}
			cur = append(cur, r)
		default:
			flush()
		}
	}
	flush()
	return words
}
