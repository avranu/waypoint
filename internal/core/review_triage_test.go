func TestTriageFeatures(t *testing.T) {
	t.Run("nothing to go on", func(t *testing.T) {
		for _, c := range []*ChangeFacts{nil, {}, {Numstat: "  \n"}} {
			if f := triageFeatures(c); !f.NoFacts || triageFloor(f) != "no_facts" {
				t.Errorf("%+v: %+v", c, f)
			}
		}
	})
	t.Run("comments and blanks", func(t *testing.T) {
		f := triageFeatures(&ChangeFacts{Numstat: "3\t1\tx/a.go\n1\t1\tdocs/a.md",
			Diff: goDiff("x/a.go", "@@ -3 +3,3 @@ func a\n-// old\n+// new\n+\n+// more\n") + goDiff("docs/a.md", "@@ -1 +1 @@\n-a\n+b\n"), Commits: 2})
		if f.Files != 2 || f.Added != 4 || f.Deleted != 2 || f.Docs != 1 || f.Code != 1 || f.CommentLines != 3 || f.BlankLines != 1 || f.CodeLines != 0 || f.Commits != 2 {
			t.Fatalf("%+v", f)
		}
	})
	t.Run("a removed line that looks like a header", func(t *testing.T) {
		f := triageFeatures(&ChangeFacts{Numstat: "0\t2\tx/a.sh", Diff: goDiff("x/a.sh", "@@ -3,2 +2,0 @@\n--- b/secret.go\n-+++ b/other.go\n")})
		if f.CodeLines != 2 || f.NewFiles != 0 || f.DeletedFiles != 0 {
			t.Fatalf("%+v", f)
		}
	})
	t.Run("lines the diff doesn't explain are code", func(t *testing.T) {
		f := triageFeatures(&ChangeFacts{Numstat: "5\t0\tx/a.go", Diff: goDiff("x/a.go", "@@ -0,0 +1 @@\n+// one\n")})
		if f.CommentLines != 1 || f.CodeLines != 4 {
			t.Fatalf("%+v", f)
		}
		if f := triageFeatures(&ChangeFacts{Numstat: "2\t0\tx/a.go"}); f.CodeLines != 2 {
			t.Fatalf("no diff: %+v", f)
		}
	})
	t.Run("only a string's text", func(t *testing.T) {
		f := triageFeatures(&ChangeFacts{Numstat: "1\t1\tx/a.go", Diff: goDiff("x/a.go", "@@ -3 +3 @@\n-\tfmt.Println(\"helo\")\n+\tfmt.Println(\"hello\")\n")})
		if f.StringLines != 2 || f.CodeLines != 0 || f.SQLStrings != 0 {
			t.Fatalf("%+v", f)
		}
		f = triageFeatures(&ChangeFacts{Numstat: "1\t1\tx/a.go", Diff: goDiff("x/a.go", "@@ -3 +3 @@\n-\tq(\"SELECT a FROM b\")\n+\tq(\"SELECT c FROM b\")\n")})
		if f.StringLines != 2 || f.SQLStrings != 2 {
			t.Fatalf("sql: %+v", f)
		}
		f = triageFeatures(&ChangeFacts{Numstat: "1\t1\tx/a.go", Diff: goDiff("x/a.go", "@@ -3 +3 @@\n-\tfoo(\"a\")\n+\tbar(\"a\")\n")})
		if f.StringLines != 0 || f.CodeLines != 2 {
			t.Fatalf("code: %+v", f)
		}
	})
	t.Run("commenting out code isn't a comment change", func(t *testing.T) {
		f := triageFeatures(&ChangeFacts{Numstat: "1\t1\tx/a.go", Diff: goDiff("x/a.go", "@@ -3 +3 @@\n-\tdelete(a)\n+\t// delete(a)\n")})
		if f.CodeLines != 1 || f.CommentLines != 1 {
			t.Fatalf("%+v", f)
		}
		if r := decideTriage(f, ReviewSkipOn, ShipAuto, 99); r.Action != triageReview {
			t.Fatalf("%+v", r)
		}
	})
	t.Run("nothing but a mode change or blank lines isn't a comment change", func(t *testing.T) {
		for name, c := range map[string]*ChangeFacts{
			"mode":                             {Numstat: "0\t0\tscripts/run.sh", Diff: "diff --git a/scripts/run.sh b/scripts/run.sh\nold mode 100644\nnew mode 100755\n"},
			"empty":                            {Numstat: "0\t0\tx/a.go", Diff: "diff --git a/x/a.go b/x/a.go\nnew file mode 100644\nindex 0000000..e69de29\n"},
			"blank":                            {Numstat: "1\t0\tx/a.go", Diff: goDiff("x/a.go", "@@ -10,0 +11 @@\n+\n")},
			"blank beside a comment elsewhere": {Numstat: "2\t0\tx/a.go", Diff: goDiff("x/a.go", "@@ -10,0 +11 @@\n+\n@@ -40,0 +42 @@\n+// explain\n")},
		} {
			if d := decideTriage(triageFeatures(c), ReviewSkipOn, ShipAuto, 99); d.Action != triageReview || d.Rule == "comments" {
				t.Errorf("%s: %+v", name, d)
			}
		}
	})
	t.Run("new, deleted, binary, unreadable", func(t *testing.T) {
		f := triageFeatures(&ChangeFacts{Numstat: "1\t0\tx/n.go\n0\t1\tx/d.go\n-\t-\tx/i.png",
			Diff: "diff --git a/x/n.go b/x/n.go\n--- /dev/null\n+++ b/x/n.go\n@@ -0,0 +1 @@\n+// new\ndiff --git a/x/d.go b/x/d.go\n--- a/x/d.go\n+++ /dev/null\n@@ -1 +0,0 @@\n-// gone\n"})
		if f.NewFiles != 1 || f.DeletedFiles != 1 || f.Binary != 1 || f.CommentLines != 2 || f.CodeLines != 0 {
			t.Fatalf("%+v", f)
		}
		if f := triageFeatures(&ChangeFacts{Numstat: "not numstat"}); triageFloor(f) != "clipped" {
			t.Fatalf("%+v", f)
		}
	})
}

// docsChange is a small change to docs.
func docsChange() *ChangeFacts {
	return &ChangeFacts{Numstat: "2\t1\tdocs/a.md\n1\t0\tREADME.md"}
}

// commentChange is a comment-only change to a file with this path.
func commentChange(path string) *ChangeFacts {
	return &ChangeFacts{Numstat: "1\t1\t" + path, Diff: goDiff(path, "@@ -3 +3 @@ func a\n-// old\n+// new\n")}
}

