// The report is what the rules are judged by: later evidence belongs to the
// branch that was assessed, and a rule's misses come only from reviews
// nothing about the change chose.
func TestReviewTriageEvidence(t *testing.T) {
	a, _, task := triageEnv(t)
	now := a.clockNow().UnixMilli()
	exec := func(q string, args ...any) int64 {
		t.Helper()
		res, err := a.s.db.W.Exec(q, args...)
		if err != nil {
			t.Fatal(err)
		}
		id, _ := res.LastInsertId()
		return id
	}
	var forge int64
	if err := a.s.db.R.QueryRow(`SELECT id FROM forges LIMIT 1`).Scan(&forge); err != nil {
		t.Fatal(err)
	}
	pr := func(n int, head string) int64 {
		t.Helper()
		url := "https://git.example/acme/app/pulls/" + itoa(n)
		id := exec(`INSERT INTO pull_requests(forge_id, repo, number, url, head_ref, created_at, updated_at) VALUES (?, 'acme/app', ?, ?, ?, ?, ?)`, forge, n, url, head, now, now)
		exec(`INSERT INTO external_links(issue_id, provider, kind, url, repo, number, title, state, created_at) VALUES (?, 'forgejo', 'pull', ?, 'acme/app', ?, 't', 'open', 1)`, task.ID, url, n)
		return id
	}
	ord := 0
	finding := func(prID int64) {
		t.Helper()
		ord++
		run := exec(`INSERT INTO bot_runs(project_id, pr_id, kind, head_sha, status, created_at) VALUES (?, ?, 'review', 'abc', 'done', ?)`, a.p.ID, prID, now)
		exec(`INSERT INTO bot_findings(run_id, pr_id, path, line, severity, claim, model, state, placement, ordinal, created_at, updated_at) VALUES (?, ?, 'x.go', 1, 'high', 'c', 'm', ?, 'inline', ?, ?, ?)`, run, prID, FindingFixed, ord, now, now)
	}
	row := func(head, rule string, would int, action, why string, found int) {
		t.Helper()
		round := exec(`INSERT INTO work_log(issue_id, kind, state, found, fixed, rejected, created_at, updated_at) VALUES (?, 'review', 'done', ?, 0, 0, ?, ?)`, task.ID, found, now, now)
		exec(`INSERT INTO review_triage(round_id, issue_id, project_id, repo, head, rule, would_skip, action, why, version, created_at) VALUES (?, ?, ?, 'acme/app', ?, ?, ?, ?, ?, 'rules-1', ?)`,
			round, task.ID, a.p.ID, head, rule, would, action, why, now)
	}
	stats := func() TriageTotals {
		t.Helper()
		st, err := a.s.GetReviewTriageStats(a.ctx, a.admin, a.p.Key, 30, false)
		if err != nil {
			t.Fatal(err)
		}
		return st.Total
	}

	reviewed := pr(1, "wp-1-code")
	skipped := pr(2, "wp-1-docs")
	finding(reviewed)
	exec(`INSERT INTO escapes(issue_id, pr_id, project_id, stage, detector, intro_pr_id, confidence, fixed_at, created_at) VALUES (?, ?, ?, 'prod', 'd', ?, 1, ?, ?)`, task.ID, reviewed, a.p.ID, reviewed, now, now)
	row("wp-1-code", "normal", 0, triageReview, "", 1)
	row("wp-1-docs", "docs", 1, triageSkip, "", 0)
	got := stats()
	if got.Useful != 1 || got.Escapes != 1 || got.UsefulOnSkip != 0 || got.EscapesOnSkips != 0 {
		t.Fatalf("the reviewed branch's evidence: %+v", got)
	}
	finding(skipped)
	got = stats()
	if got.Useful != 2 || got.UsefulOnSkip != 1 {
		t.Fatalf("the skipped branch's evidence: %+v", got)
	}

	row("wp-1-code", "normal", 0, triageReview, "", 0)
	if got = stats(); got.Useful != 2 || got.Escapes != 1 {
		t.Fatalf("assessed twice: %+v", got)
	}

	// Asked-for and floor reviews aren't samples of what the rules skip.
	row("a", "docs", 1, triageReview, triageWhyAsked, 5)
	row("b", "floor:binary", 0, triageReview, "", 7)
	if got = stats(); got.Sampled != 0 || got.SampledFoundAny != 0 || got.SampledFound != 0 {
		t.Fatalf("not samples: %+v", got)
	}
	row("c", "docs", 1, triageReview, triageWhyHoldout, 2)
	row("d", "tests", 1, triageReview, triageWhyShadowRule, 0)
	row("e", "docs", 1, triageReview, triageWhyModeShadow, 1)
	row("f", "docs", 1, triageReview, triageWhyModeOff, 0)
	if got = stats(); got.Sampled != 4 || got.SampledFoundAny != 2 || got.SampledFound != 3 {
		t.Fatalf("samples: %+v", got)
	}
}

